import { mkdir, cp, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
const destination = process.argv[2];
if (!destination) throw new Error('Usage: node scripts/export-swift-package.mjs <destination>');
const revision = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const root = resolve(destination);
await mkdir(root, { recursive: true });
await cp('Sources/DiffViewKit', `${root}/Sources/DiffViewKit`, { recursive: true });
await cp('THIRD_PARTY_NOTICES.md', `${root}/THIRD_PARTY_NOTICES.md`);
await writeFile(`${root}/Package.swift`, `// swift-tools-version: 6.0\nimport PackageDescription\nlet package = Package(name: "DiffViewKit", platforms: [.macOS(.v14)], products: [.library(name: "DiffViewKit", targets: ["DiffViewKit"])], targets: [.target(name: "DiffViewKit", resources: [.copy("Resources/Web")])])\n`);
await writeFile(`${root}/UPSTREAM.md`, `# Diff View snapshot\n\nSource: diff-view\nRevision: ${revision}\n\nGenerated by npm run build and scripts/export-swift-package.mjs. Do not edit this snapshot; change the independent project and export again. All Web resources are bundled; no npm installation is needed by the consuming application.\n`);
console.log(`Exported ${revision} to ${root}`);
